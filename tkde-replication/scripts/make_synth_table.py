"""Build Table V (synthetic detection quality) from synthetic/results/.

Companion to ``make_tables.py``, which covers the real streams. Reads the
per-seed CSVs written by ``run_synthetic.py`` and emits
``tables/table_synth.tex`` in the layout the manuscript uses: two blocks of two
scenarios, four metrics per scenario, best value per block in bold.

NaN policy, which the table legend must state
---------------------------------------------
``calculate_drift_metrics`` returns NaN for MTFA when a seed produced fewer than
two false alarms, and for MTD when nothing was detected. MTR, being MTFA/MTD,
inherits both. Those seeds are dropped from that metric's mean rather than
counted as zero, and a metric with no usable seed at all prints ``--``. The
number of usable seeds per cell goes into the companion CSV, so a mean over
three seeds is never mistaken for a mean over ten.
"""

from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

SCENARIO_TITLES = {
    "S1": "S1 -- gradual correlation-structure drift",
    "S2": "S2 -- abrupt conditional-dependence change",
    "S3": "S3 -- incremental time-varying correlations",
    "S4": "S4 -- recurring covariance-template switches",
}

DISPLAY = [
    ("BayesianNonparametricDetectionMethod", "BNDM"),
    ("ClusteredStatisticalTestDriftDetectionMethod", "CSDDM"),
    ("DiscriminativeDriftDetector2019", "D3"),
    ("ImageBasedDriftDetector", "IBDD"),
    ("OneClassDriftDetector", "OCDD"),
    ("SemiParametricLogLikelihood", "SPLL"),
    ("UDetect", "UDetect"),
    ("FasanoFranceschiniWindow", "FFWIN"),
]

# metric -> (better direction, decimals)
METRICS = {
    "mdr": ("min", 2),
    "mtd": ("min", 2),
    "mtfa": ("max", 2),
    "mtr": ("max", 2),
}


def load(results_dir: Path):
    """rows keyed by (scenario, detector) -> list of per-seed dicts."""
    data: dict[tuple[str, str], list[dict]] = {}
    for path in sorted(results_dir.glob("*/*_synthetic.csv")):
        with path.open(newline="", encoding="utf-8") as handle:
            for row in csv.DictReader(handle):
                data.setdefault((row["scenario"], row["detector"]), []).append(row)
    return data


def mean_of(rows, metric):
    """Mean over the seeds where the metric is defined; (None, 0) if none is."""
    values = []
    for row in rows:
        raw = (row.get(metric) or "").strip()
        if not raw:
            continue
        try:
            value = float(raw)
        except ValueError:
            continue
        if math.isnan(value) or math.isinf(value):
            continue
        values.append(value)
    if not values:
        return None, 0
    return sum(values) / len(values), len(values)


def cell(value, decimals, best):
    if value is None:
        return "--"
    text = "{:.{d}f}".format(value, d=decimals)
    return "\\textbf{" + text + "}" if best else text


def block(data, scenario):
    """One scenario's rows: [(label, [formatted cells])]."""
    means = {}
    for key, _ in DISPLAY:
        rows = data.get((scenario, key), [])
        means[key] = {m: mean_of(rows, m) for m in METRICS}

    best = {}
    for metric, (direction, _) in METRICS.items():
        values = [means[k][metric][0] for k, _ in DISPLAY if means[k][metric][0] is not None]
        best[metric] = (min(values) if direction == "min" else max(values)) if values else None

    out = []
    for key, label in DISPLAY:
        cells = []
        for metric, (_, decimals) in METRICS.items():
            value, _ = means[key][metric]
            is_best = (
                value is not None
                and best[metric] is not None
                and abs(value - best[metric]) < 1e-9
            )
            cells.append(cell(value, decimals, is_best))
        out.append((label, cells))
    return out, means


HEADER = (
    r"\textbf{Detector} & \textbf{MDR}\,$\downarrow$ & \textbf{MTD}\,$\downarrow$ & "
    r"\textbf{MTFA}\,$\uparrow$ & \textbf{MTR}\,$\uparrow$"
)


def render(data):
    lines = [
        r"% Generated by scripts/make_synth_table.py -- do not edit by hand.",
        r"\begin{table*}[!t]",
        r"\centering",
        r"\caption{Detection quality on the four synthetic scenarios with prescribed "
        r"correlation drift and stable marginals. Best value per block in bold. "
        r"\ac{MTR} is reported with its constituents, since a high \ac{MTR} may be "
        r"driven by stability (\ac{MTFA}) rather than coverage (\ac{MDR}). A dash "
        r"marks a metric that is undefined on every seed: \ac{MTFA} needs two false "
        r"alarms and \ac{MTD} needs one detection.}",
        r"\label{tab:synth_all}",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{5pt}",
        r"\renewcommand{\arraystretch}{1.08}",
        r"\begin{tabular}{@{}lcccc@{\hspace{2.2em}}lcccc@{}}",
        r"\toprule",
    ]
    summary = {}
    for left, right in (("S1", "S2"), ("S3", "S4")):
        rows_l, means_l = block(data, left)
        rows_r, means_r = block(data, right)
        summary[left], summary[right] = means_l, means_r
        lines.append(
            r"\multicolumn{5}{c}{\textbf{" + SCENARIO_TITLES[left] + r"}} &"
        )
        lines.append(
            r"\multicolumn{5}{c}{\textbf{" + SCENARIO_TITLES[right] + r"}} \\"
        )
        lines.append(r"\cmidrule(r){1-5}\cmidrule(l){6-10}")
        lines.append(HEADER + " &")
        lines.append(HEADER + r" \\")
        lines.append(r"\midrule")
        for (label_l, cells_l), (label_r, cells_r) in zip(rows_l, rows_r):
            lines.append(
                "{:<8}& {} & {:<8}& {} \\\\".format(
                    label_l, " & ".join(cells_l), label_r, " & ".join(cells_r)
                )
            )
        lines.append(r"\midrule" if left == "S1" else r"\bottomrule")
    lines += [r"\end{tabular}", r"\end{table*}"]
    return "\n".join(lines) + "\n", summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", default="synthetic/results")
    parser.add_argument("--out", default="tables/table_synth.tex")
    parser.add_argument("--summary", default="tables/table_synth_summary.csv")
    args = parser.parse_args()

    data = load(ROOT / args.results)
    if not data:
        raise SystemExit("no synthetic results under " + str(ROOT / args.results))

    tex, summary = render(data)
    out_path = ROOT / args.out
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(tex, encoding="utf-8")
    print("wrote", out_path)

    with (ROOT / args.summary).open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["scenario", "detector", "metric", "mean", "n_usable_seeds"])
        for scenario in sorted(summary):
            for key, label in DISPLAY:
                for metric in METRICS:
                    value, n = summary[scenario][key][metric]
                    writer.writerow(
                        [scenario, label, metric, "" if value is None else round(value, 4), n]
                    )
    print("wrote", ROOT / args.summary)


if __name__ == "__main__":
    main()
