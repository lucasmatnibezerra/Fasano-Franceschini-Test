"""Build the tuned synthetic table from ``tune_synthetic.py eval`` output.

Companion to ``make_synth_table.py``, which covers the frozen configurations.
Reads ``synthetic/tuning/eval_delta<delta>.csv`` (one row per detector,
scenario and held-out seed, each detector at the configuration it selected on
the tuning seeds) and emits ``tables/table_synth_tuned.tex``: per scenario,
detection F1 at tolerance ``delta``, the benchmark's MDR, and the number of
alarms, as mean over the held-out seeds, F1 with its standard deviation.
Best F1 per scenario in bold.

With ``--offset``, FFWIN's rows, configurations and alarm positions come from
the shifted-stream phase (``tune_synthetic.py ... --offset``) while the
baselines keep their unshifted runs; this is the version the manuscript quotes.

It also writes ``tables/table_synth_tuned_configs.csv``, the configuration
each detector selected per scenario, and
``tables/table_synth_tuned_delta_sensitivity.csv``, the F1 of those same
configurations at other tolerances, for the replication package.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import statistics
from pathlib import Path

from make_synth_table import DISPLAY

ROOT = Path(__file__).resolve().parent.parent
SCENARIOS = ["S1", "S2", "S3", "S4"]
SENSITIVITY_DELTAS = [500, 1000, 1500, 2000]
FF = "FasanoFranceschiniWindow"


def load(path: Path):
    data: dict[tuple[str, str], list[dict]] = {}
    with path.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            data.setdefault((row["scenario"], row["detector"]), []).append(row)
    return data


def mean_sd(rows, key):
    values = [float(r[key]) for r in rows if r[key] not in ("", "nan")]
    values = [v for v in values if not math.isnan(v)]
    if not values:
        return None, None
    return statistics.fmean(values), (statistics.stdev(values) if len(values) > 1 else 0.0)


NUMBER_WORDS = {3: "three", 7: "seven", 10: "ten"}

OFFSET_NOTE = (
    r" \ac{FFWIN} is tuned and scored on streams shifted by a random offset per "
    r"seed, since with $s{=}W$ its comparison grid can coincide with the drift times."
)


def render(data, delta, n_seeds, note=""):
    f1 = {(s, k): mean_sd(data.get((s, k), []), "f1") for s in SCENARIOS for k, _ in DISPLAY}
    best = {s: max((f1[s, k][0] or 0.0) for k, _ in DISPLAY) for s in SCENARIOS}

    head = " & ".join(
        r"\multicolumn{3}{c}{\textbf{" + s + "}}" for s in SCENARIOS
    )
    sub = " & ".join([r"\textbf{F1}\,$\uparrow$ & \textbf{MDR}\,$\downarrow$ & \textbf{\#al.}"] * len(SCENARIOS))
    rules = "".join(
        r"\cmidrule(lr){{{}-{}}}".format(2 + 3 * i, 4 + 3 * i) for i in range(len(SCENARIOS))
    )
    lines = [
        r"% Generated by scripts/make_tuning_table.py -- do not edit by hand.",
        r"\begin{table*}[!t]",
        r"\centering",
        r"\caption{Detection on the synthetic scenarios with the best configuration "
        r"per scenario, an oracle (means over " + NUMBER_WORDS.get(n_seeds, str(n_seeds))
        + r" held-out seeds, F1 $\pm$ sd; F1 at $\Delta{=}" + str(delta)
        + r"$; \#al.: alarms per stream). Best F1 in bold." + note + "}",
        r"\label{tab:synth_tuned}",
        r"\tablestyle",
        r"\begin{tabular}{@{}l" + "ccc" * len(SCENARIOS) + r"@{}}",
        r"\toprule",
        r"& " + head + r" \\",
        rules,
        r"\textbf{Detector} & " + sub + r" \\",
        r"\midrule",
    ]
    for key, label in DISPLAY:
        cells = []
        for s in SCENARIOS:
            rows = data.get((s, key), [])
            m_f1, sd_f1 = f1[s, key]
            m_mdr, _ = mean_sd(rows, "mdr")
            m_al, _ = mean_sd(rows, "n_alarms")
            if m_f1 is None:
                cells += ["--"] * 3
                continue
            text = "{:.2f}".format(m_f1)
            if best[s] > 0 and abs(m_f1 - best[s]) < 1e-9:
                text = r"\textbf{" + text + "}"
            text += r" $\pm$ {:.2f}".format(sd_f1)
            cells += [
                text,
                "--" if m_mdr is None else "{:.2f}".format(m_mdr),
                "{:.1f}".format(m_al),
            ]
        lines.append("{:<8}& {} \\\\".format(label, " & ".join(cells)))
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--delta", type=int, default=1000)
    parser.add_argument("--tuning", default="synthetic/tuning")
    parser.add_argument("--out", default="tables/table_synth_tuned.tex")
    parser.add_argument("--configs", default="tables/table_synth_tuned_configs.csv")
    parser.add_argument("--sensitivity", default="tables/table_synth_tuned_delta_sensitivity.csv")
    parser.add_argument("--offset", action="store_true",
                        help="take FFWIN from the shifted-stream phase (see module docstring)")
    args = parser.parse_args()

    tuning = ROOT / args.tuning
    data = load(tuning / "eval_delta{}.csv".format(args.delta))
    selected = json.loads(
        (tuning / "selected_delta{}.json".format(args.delta)).read_text(encoding="utf-8")
    )
    if args.offset:
        data = {k: v for k, v in data.items() if k[1] != FF}
        data.update({k: v for k, v in load(tuning / "eval_offset_delta{}.csv".format(args.delta)).items()
                     if k[1] == FF})
        selected = [s for s in selected if s["detector"] != FF] + json.loads(
            (tuning / "selected_offset_delta{}.json".format(args.delta)).read_text(encoding="utf-8"))
    n_seeds = max(len({r["seed"] for r in rows}) for rows in data.values())

    out = ROOT / args.out
    out.write_text(render(data, args.delta, n_seeds, OFFSET_NOTE if args.offset else ""),
                   encoding="utf-8", newline="\n")
    print("wrote", out)

    labels = dict(DISPLAY)
    with (ROOT / args.configs).open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["scenario", "detector", "cfg", "f1_tune", "params"])
        for s in sorted(selected, key=lambda s: (s["scenario"], s["detector"])):
            writer.writerow([
                s["scenario"], labels.get(s["detector"], s["detector"]), s["cfg"],
                round(s["f1_tune"], 4), json.dumps(s["params"], sort_keys=True),
            ])
    print("wrote", ROOT / args.configs)

    # F1 of the selected configurations at other tolerances, recomputed from
    # the stored alarm positions. Selection stays at --delta.
    from tune_synthetic import detection_f1

    chosen = {(s["detector"], s["scenario"], s["cfg"]) for s in selected}
    scores: dict[tuple[str, str], list[list[float]]] = {}
    raws = [tuning / "eval_delta{}".format(args.delta) / "_raw"]
    if args.offset:
        raws.append(tuning / "eval_offset_delta{}".format(args.delta) / "_raw")
    for path in sorted(p for raw in raws for p in raw.rglob("*.json")):
        r = json.loads(path.read_text(encoding="utf-8"))
        if args.offset and (r["detector"] == FF) != ("offset" in str(path)):
            continue
        if (r["detector"], r["scenario"], r["cfg"]) not in chosen:
            continue
        scores.setdefault((r["scenario"], r["detector"]), []).append(
            [detection_f1(r["known"], r["alarms"], d)[0] for d in SENSITIVITY_DELTAS]
        )
    out = ROOT / args.sensitivity
    with out.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["scenario", "detector", "n_seeds"] + ["f1_delta{}".format(d) for d in SENSITIVITY_DELTAS])
        for (scenario, detector), rows in sorted(scores.items()):
            means = [round(statistics.fmean(col), 4) for col in zip(*rows)]
            writer.writerow([scenario, labels.get(detector, detector), len(rows)] + means)
    print("wrote", out)


if __name__ == "__main__":
    main()
